% lis_ana01_ICA_TP9u10_concat.m
%
% This script runs an independent component analysis (ICA) on the raw 
% data. 
%
% The following steps are performed:
%           - Read in Data
%           - Concatenating all 3 datasets from one participant
%           - Filter data from 1-40 Hz for ICA training
%           - Finding bad channels, plotting and rejecting them
%           - Epoch data (dummy epochs) and remove artifactual epochs for ICA
%           - Run ICA with the runica algorithm and the additional option of PCA
%             on the cleaned concatenated data
%           - Loading original (not concatenated) data and rejecting bad
%             channels there 
%           - Save ICA decomposition to original (not concatenated) data
%
% Input:    - EEGLAB SET files with digitized channel locations
%             generated by lis_ana00_convert_rawdata.m
%           - Three EEG datasets per participant
%
% Output:   - Bad channel plots (.png)
%           - ICA decomposition and bad channels per participant (.mat)
%           - Individual EEG datasets with stored ICA decomposition (.set)
%           - Summary of bad channels for all datasets (.csv)
% 
% Adapted by Linn Schwarz 15/12/2025
% Martin Bleichner 11/01/2018
% Maren Stropahl 25/09/2017
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

%% DIRECTORIES

clear; close all;

% execute this script from within the 'scripts' folder 
MAINPATH = fileparts(pwd);
PATHIN  = fullfile(MAINPATH,'rawdata_digitized',filesep);           % path containing rawdata                   
PATHOUT = fullfile(MAINPATH, 'data','lis01',filesep);               % path for script output

% create output folder if it does not exist yet
if ~exist(PATHOUT)
    mkdir(PATHOUT);
end

% locate rawdata-sets
cd(PATHIN)
list=dir('*.set');                                                  % reads all .set files in PATHIN
len=length(list);                                                   % total number of datasets that will be evaluated

% Extract participant IDs from the first 13 characters of each filename.
% NOTE: This assumes that all filenames follow the same naming convention
% and that the first 13 characters uniquely identify a participant.
subjects = unique(cellfun(@(x) x(1:13), {list.name}, 'uni', 0));   

%% PARAMETERS

HP = 1;         % cut-off frequency high-pass filter [Hz] only for ICA 
LP = 40;        % cut-off frequency low-pass filter [Hz] only for ICA 
SRATE = 250;    % target sampling rate [Hz] (resampling currently disabled)
HP_ord= 414;    % high-pass filter order depends on sampling rate; o = pop_firwsord('hamming', 250, 2);
LP_ord= 84;     % low-pass filter order depends on sampling rate; o = pop_firwsord('hamming', 250, (0.25*40)); 
PRUNE = 2;      % artifact rejection threshold in SD (for ICA only)
% PCA = 1;      % choose PCA option for ICA
PCA = 0;        % no PCA for 32 chan
PCADIMS = 50;   % PCA dimension if PCA option is true
%% PREPARE DATA AND RUN ICA

% start eeglab
[ALLEEG EEG CURRENTSET ALLCOM] = eeglab;

% Bad-channel criterion:
% channels with SD > mean(channel SD) + factor * SD(channel SD)
factor = 2.5; 

% initializing counter
counter = 1;

% loop over all .set subjects   
for sub = 1:length(subjects)

    % finding all three datasets per person
    idx = find(contains({list.name}, subjects{sub}));
    files_sub = {list(idx).name};

    % loading all three datasets per person and concatenating them 
    EEG = [];
    for f = 1:length(files_sub)
        tmp = pop_loadset('filename', files_sub{f}, 'filepath', PATHIN);

        if f == 1
            EEG = tmp;
        else
            EEG = pop_mergeset(EEG, tmp);
        end
    end

    EEG.setname = [subjects{sub} '_concat'];

    % apply low pass filter
    EEG = pop_firws(EEG, 'fcutoff', LP, 'ftype', 'lowpass', 'wtype', 'hamming' , 'forder', LP_ord);
    % downsample data - may be an optional step (not needed here, since data is collected with srate of 250 Hz)
    % EEG = pop_resample(EEG, SRATE);
    % apply high pass filter
    EEG = pop_firws(EEG, 'fcutoff', HP, 'ftype', 'highpass', 'wtype', 'hamming',...
        'forder', HP_ord);

    channel.vari = std(EEG.data(1:EEG.nbchan,:),0,2);                               % calcualte std of every channel 
    channel.crit = mean(channel.vari)+std(channel.vari)*factor;                     % calculate threshold
    channel.badc = find(channel.vari > channel.crit)';                              % find the bad channels

    % calculate channel-wise SD in consecutive 30-s windows for visualization
    sec = 30;
    LeWin = EEG.srate*sec;                                                                  % define window length
    timeVec = 0 : 1/EEG.srate : sec-1/EEG.srate;                                            % define time vector
    idx_loop = 1:LeWin:size(EEG.data,2);                                                    % check how loop index will look like
    sd_t = zeros(EEG.nbchan, length(idx_loop));                                             % pre-allocate matrix of sd over time
    row_count = 1;                                                                          % set counter

    for idx = 1: LeWin: size(EEG.data,2)-LeWin

        signal = EEG.data(:,idx:idx+(LeWin-1));                                             % get short extract from data
        sd_t(:, row_count) = std(signal, [],2);                                             % calc standard deviation over time per channel
        row_count = row_count +1;                                                           % update counter

    end

    % set up the figure with a larger size
    fig_bad_chan = figure('units','normalized','outerposition', [0 0 1 1]);                 % fig = figure('Units', 'pixels', 'Renderer', 'painters'); [100, 100, 800, 600]

    subplot(2, 2, [1, 3]);
    topoplot(channel.vari, EEG.chanlocs, 'electrodes', 'numpoint', 'chaninfo', EEG.chaninfo, 'whitebk', 'on', 'shading', 'interp');

    subplot(2, 2, 4);
    plot(channel.vari, 'k', 'LineWidth', 1);                                                % plot lines of channel stds with threshold
    hold on;
    yline(channel.crit, 'r--', 'LineWidth', 2);
    xlim([1 EEG.nbchan]);
    title(['Outliers: ', mat2str(channel.badc)], 'Interpreter', 'none');
    subtitle(['Threshold: [Mean SD + ', num2str(factor), ' × SD]']);
    xlabel('Electrodes');
    ylabel('SD');
    grid on;
    axis tight;

    ax1 = subplot(2, 2, 2);                                                                 % create colormap for channel stds over time
    imagesc(sd_t);
    colorbar;
    colormap(ax1, turbo);
    xlabel('Time [sec]');
    ylabel('Electrodes');
    title('SD over time');
    subtitle(['Windows of ', num2str(sec), ' [sec]']);
    sgt = sgtitle(['Electrode artefacts: [', subjects{sub}, ']'], 'Interpreter', 'none');   % title for whole plot

    % save figure
    saveas(gcf, fullfile(PATHOUT, [subjects{sub} '_badchan_plot.png']));
    close(fig_bad_chan);

    % rejecting bad channels
    if ~isempty(channel.badc)
        EEG = pop_select(EEG, 'nochannel', channel.badc);
    end
    
    % segment continuous data into 1-s dummy epochs for artifact rejection
    EEG = eeg_regepochs(EEG, 'recurrence', 1, 'eventtype', '999');
    EEG = eeg_checkset(EEG, 'eventconsistency');
    
    % remove epochs with artefacts to improve ICA training
    EEG = pop_jointprob(EEG, 1, [1:size(EEG.data,1)], PRUNE, PRUNE, 0, 1, 0);

    % run ICA optional with or without PCA
    % a window will pop-up as soon as ICA starts which allows to interrupt
    % the ICA process. Please only press if you want to cancel the process
    if PCA == 1
        EEG = pop_runica(EEG, 'icatype', 'runica', 'extended', 1, 'pca',...
            PCADIMS);
    else
        EEG = pop_runica(EEG, 'icatype', 'runica', 'extended', 1);
    end

    % store ICA decomposition in temporary variables
    ICA.icawinv   = EEG.icawinv;
    ICA.icaweights = EEG.icaweights;
    ICA.icasphere  = EEG.icasphere;
    ICA.badchans   = channel.badc;

    % saving ICA decomposition and bad channels per participant
    save(fullfile(PATHOUT, ['ICA_' subjects{sub} '.mat']), 'ICA');

    % Apply the ICA decomposition obtained from the filtered, concatenated
    % training data to each original dataset. The same channels that were
    % excluded during ICA training must be removed before assigning the
    % ICA decomposition.
    for f = 1:length(files_sub)

        fname = strrep(files_sub{f}, '.set', '');

        % load raw file
        EEG = pop_loadset('filename', files_sub{f}, 'filepath', PATHIN);

        % extract names of bad channels
        if ~isempty(ICA.badchans)
            bad_names = {EEG.chanlocs(ICA.badchans).labels};
        else
            bad_names = {'none'};
        end

        % store results
        results(counter).dataset   = fname;
        results(counter).badchans  = bad_names;

        % write labels of bad channels to rawdata
        if ~isempty(ICA.badchans)
            EEG.badchannels = {EEG.chanlocs(ICA.badchans).labels};
        else
            EEG.badchannels = {'none'};
        end

        % reject same bad channels as during ICA training
        if ~isempty(ICA.badchans)
            EEG = pop_select(EEG, 'nochannel', ICA.badchans);
        end

        % insert ICA decomposition
        EEG.icawinv   = ICA.icawinv;
        EEG.icasphere = ICA.icasphere;
        EEG.icaweights = ICA.icaweights;
        EEG = eeg_checkset(EEG);

        % save dataset with ICA
        EEG.setname = [fname '_withICA'];
        pop_saveset(EEG, 'filename', [EEG.setname '.set'], 'filepath', PATHOUT);

        counter = counter+1;

    end
end


% save results
T = struct2table(results);
writetable(T, fullfile(PATHOUT, 'bad_channels_summary.csv'));

% return to scripts folder
cd(fullfile(MAINPATH, 'scripts', filesep));

% end of script
