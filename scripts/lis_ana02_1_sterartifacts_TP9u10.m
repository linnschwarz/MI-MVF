% lis_ana02_1_sterartifacts_TP9u10.m
%
% The following steps are performed:  
%       1. - run IClabel and eyecatch to find ICA components reflecting 
%            artefacts for each dataset: eye, heart, muscle
%          - save components in .mat file
%       3. - reload data file with saved ICA decomposition
%          - store selected components as EEG.badcomps in each dataset
%          - save all ICA components for each dataset as a .png graphic for
%            inspection of ICA components 
%          - remove (by IClabel and eyecatch) selected components
%          - check whether TP9 or TP10 were originally bad channels, if
%            yes, also remove the other one
%          - interpolate bad channels
%          - save new dataset in PATHOUT with rejected components
%
% Input:   - EEGLAB SET files with stored ICA decomposition and bad-channel
%            information generated by lis_ana01_ICA_TP9u10_concat.m
%          - Original EEGLAB SET files with complete channel locations
%            generated by lis_ana00_convert_rawdata.m (used as reference
%            for bad-channel interpolation)
%
% Output:  - ICA component plots per dataset (.png)
%          - EyeCatch plots per dataset (.png)
%          - ICA-cleaned EEG datasets with interpolated bad channels (.set)
%          - Automatically flagged ICA components for all datasets (.mat)
%
% Adapted by Linn Schwarz 15/12/2025
% Adapted by María Paula Villabona 30/12/2022
