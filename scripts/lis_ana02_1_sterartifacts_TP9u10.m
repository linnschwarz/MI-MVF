%% DIRECTORIES

clear; close all; 

% execute this script from within the 'scripts' folder 
MAINPATH= fileparts(pwd);
PATHIN  = fullfile(MAINPATH,'data','lis01',filesep);      % path containing input data                  
PATHOUT = fullfile(MAINPATH, 'data','lis02_1',filesep);  % path for script output

% create output folder if it does not exist yet
if ~exist(PATHOUT)
    mkdir(PATHOUT);
end
 
% locate datasets containing ICA decomposition
cd(PATHIN)
list=dir('*.set');  % reads all .set files in PATHIN
len=length(list);   % total number of datasets that will be evaluated
fname=cell(1,len);   % create a file name cell array
 
% start eeglab
[ALLEEG EEG CURRENTSET ALLCOM] = eeglab;

%% 1. IDENTIFYING ARTIFACTUAL ICA COMPONENTS USING ICLABEL AND EYECATCH

% loop through each .set file
for s = 1:len

    % load the  dataset
    fname{s} = strrep(list(s).name, '_withICA.set', '');
    EEG = pop_loadset('filename', [fname{s}, '_withICA.set'], 'filepath', PATHIN);

    % define number of components
    ncomp= size(EEG.icaweights, 1);
    
    % run IClabel on the dataset
    EEG = pop_iclabel(EEG, 'default');
    
    % find the components reflecting artifacts
    eye = [];
    muscle = [];
    heart = [];

    for c = 1:ncomp
        % extract probability vector for component c
        probs = EEG.etc.ic_classification.ICLabel.classifications(c,:);

        % classes in ICLabel (7 labels)
        % {'Brain','Muscle','Eye','Heart','Line Noise','Channel Noise','Other'}

        % threshold for eye components: 0.7
        if probs(strcmp(EEG.etc.ic_classification.ICLabel.classes, 'Eye')) > 0.7
            eye(end+1) = c;
            continue; % Prevent double-labeling
        end

        % threshold for muscle components: 0.8
        if probs(strcmp(EEG.etc.ic_classification.ICLabel.classes, 'Muscle')) > 0.8
            muscle(end+1) = c;
        end

        % threshold for heart components: 0.8
        if probs(strcmp(EEG.etc.ic_classification.ICLabel.classes, 'Heart')) > 0.8
            heart(end+1) = c;
        end
    end

    % run eyecatch
    eyeDetector = eyeCatch;                                                 % create an object from the class
    [isEye, similarity, scalpmapObj] = eyeDetector.detectFromEEG(EEG);      % detect eye ICs
    eye_numb = find(isEye);                                                 % display the IC numbers for eye ICs (since isEye is a logical array)
    scalpmapObj.plot(isEye);                                                % plot eye ICs
    saveas(gcf, [PATHOUT, fname{s}, '_eyecatch'], 'png');
    close;

    % concatenate the components reflecting artifacts from this dataset in the badcomps field
    concat_badcomps = [eye, muscle, heart, eye_numb];
    EEG.badcomps = unique(concat_badcomps);
    allbadcomps(s).subject = fname{s};
    allbadcomps(s).badcomps = EEG.badcomps;
end
save([PATHOUT 'IClabel'], 'allbadcomps')

%% 2. MAKE FINAL SELECTION OF BAD COMPONENTS
% --> this is done manually between script lis_ana02_1 and lis_ana02_2
% --> for more information read script documentation of lis_ana02_2

% load([PATHOUT 'IClabel'], 'allbadcomps')
% 
% %adding or eliminating some components from the ones automatically chosen

%% 3. REMOVE COMPONENTS FROM ORIGINAL DATASET 

% find components marked for each dataset, store components in EEG.badcomps
% and remove selected components from dataset
for s = 1:len

    % load dataset with ICA decomposition again
    fname{s}= strrep(list(s).name, '_withICA.set', '');
    EEG = pop_loadset('filename', [fname{s}, '_withICA.set'], 'filepath', PATHIN);
    
    % find selected components for each dataset and save as badcomps in EEG
    % structure
    EEG.badcomps = allbadcomps(s).badcomps;
     
    % plot components with note about badcomps and save as
    % .png in PATHOUT folder
    % pop_topoplot(EEG, 0, [1:size(EEG.icawinv,2)], [fname{s}, ...
    %         ' removed components: ', num2str(EEG.badcomps)], [6 10], 0, ...
    %         'electrodes', 'off');
    numComponents = size(EEG.icawinv, 2);                                   % number of ICA components
    EEG = pop_iclabel(EEG, 'default');                                      % using IClabel to classify components
    pop_viewprops(EEG, 0, [1:numComponents],'brain');                       % Plotting with percentage values
    sgtitle([' removed components: ', num2str(EEG.badcomps)]);
    filename = strrep(fname{s}, '_ica', '_badcomps');
    saveas(gcf, [PATHOUT, filename], 'png');
    close;

    % remove selected components from dataset
    EEG = pop_subcomp(EEG, [EEG.badcomps], 0);
    EEG = eeg_checkset(EEG);

    % check whether TP9 or TP10 were originally bad channels, if
    % yes, also remove the other one
    if isfield(EEG, 'badchannels')

        % check whether TP9 or TP10 were originally bad channels
        mastoid_bad = any( strcmp(EEG.badchannels, 'TP9') ) || ...
            any( strcmp(EEG.badchannels, 'TP10') );

        if mastoid_bad
            fprintf('Symmetric mastoid removal in %s (TP9/TP10)\n', fname{s});

            % find indices if still present
            idx_TP9 = find(strcmp({EEG.chanlocs.labels}, 'TP9'));
            idx_TP10 = find(strcmp({EEG.chanlocs.labels}, 'TP10'));

            mastoids_to_remove = [idx_TP9, idx_TP10];

            if ~isempty(mastoids_to_remove)
                % store removed mastoid channel names
                removed_mastoids = {EEG.chanlocs(mastoids_to_remove).labels};

                % remove channels
                EEG = pop_select(EEG, 'nochannel', mastoids_to_remove);

                % add removed mastoids to EEG.badchannels
                if isfield(EEG, 'badchannels') && ~strcmp(EEG.badchannels{1}, 'none')
                    EEG.badchannels = [EEG.badchannels, removed_mastoids];
                else
                    EEG.badchannels = removed_mastoids;
                end
            end
        end
    end

    % interpolating bad channels
    if isfield(EEG, 'badchannels') && ~strcmp(EEG.badchannels{1}, 'none')
        % loading channel positions from original dataset (with all channels)
        origEEG = pop_loadset('filename', [fname{s} '.set'], ...
            'filepath', fullfile(MAINPATH, 'rawdata_digitized'));
        EEG = pop_interp(EEG, origEEG.chanlocs, 'spherical');
    end

    % save ICA cleaned dataset in lis02_1
    EEG.setname = [fname{s}, '_cleaned_interp'];
    EEG = pop_saveset( EEG, 'filename', [EEG.setname, '.set'], 'filepath',...
        PATHOUT);
end
cd(fullfile(MAINPATH, 'scripts', filesep));  

% end of script
